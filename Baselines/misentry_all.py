def _ms_witness_priority(clean, zoo, x0):
    """Select representative reject models with relatively divergent logits.

    Always explore RTAL before near-identical last-layer fine-tuned members.
    This is a search order, not removal of any zoo from acceptance checks.
    """
    x = x0.detach().to(MS_DEVICE).unsqueeze(0)
    with torch.no_grad():
        zp = ms_logits(clean, x)
        scores=[]
        for j,z in enumerate(zoo):
            zr=ms_logits(z,x)
            kl=float(ms_kl_p_r(zp,zr).mean().detach().cpu())
            typ=j//max(1,MISENTRY_ZOO_MODELS_PER_TYPE)
            scores.append((j,kl,typ))
    priority=[]
    for typ in (2,1,0):
        priority.extend(j for j,_,t in sorted(scores,key=lambda r:r[1],reverse=True) if t==typ)
    return priority[:max(1,min(MISENTRY_TARGETED_MODELS,len(priority)))]

def _ms_margin_search(clean, zoo, clean_bound, zoo_bounds, x0, seed):
    """Optional class-margin warm start for the *unchanged* hard constraints.

    Search for x where the protected model keeps its current top class while
    a zoo model prefers another class, with both entropy constraints checked
    by ms_candidate_status. Model weights are never changed during search.
    """
    if not MISENTRY_TARGETED_FALLBACK:
        return None
    x0=x0.detach().to(MS_DEVICE).unsqueeze(0).clamp(0.0,1.0)
    with torch.no_grad():
        protected_label=int(ms_logits(clean,x0).argmax(1).item())
    best=None
    for pj,j in enumerate(_ms_witness_priority(clean,zoo,x0.squeeze(0))):
        for restart in range(max(1,MISENTRY_TARGETED_PAIR_RESTARTS)):
            x=x0.clone()
            if restart:
                rng=torch.Generator().manual_seed(int(seed)+7919*pj+1009*restart)
                jitter=torch.randn(tuple(x.shape),generator=rng,dtype=x.dtype).to(x.device)
                x=ms_project_l2(x0 + 0.15 * MISENTRY_EPS_L2 * ms_unit_grad(jitter), x0).detach()
            for step in range(1,MISENTRY_TARGETED_STEPS+1):
                xv=x.detach().requires_grad_(True)
                zc=ms_logits(clean,xv)
                zr=ms_logits(zoo[j],xv)
                if not (torch.isfinite(zc).all() and torch.isfinite(zr).all()):
                    break
                # Target the top-1 decision boundary directly, while preserving
                # the protected-model label and evaluating the same constraints.
                other_mask=torch.ones_like(zc,dtype=torch.bool)
                other_mask[:,protected_label]=False
                c_other=zc.masked_fill(~other_mask,-torch.inf).max(dim=1).values
                r_other=zr.masked_fill(~other_mask,-torch.inf).max(dim=1).values
                t=max(0.1,MISENTRY_TARGETED_TEMPERATURE)
                margin=MISENTRY_TARGETED_MARGIN
                clean_preserve=t*F.softplus((c_other+margin-zc[:,protected_label])/t).mean()
                reject_flip=t*F.softplus((zr[:,protected_label]+margin-r_other)/t).mean()
                hc=ms_softmax_entropy_from_logits(zc).mean()
                hr=ms_softmax_entropy_from_logits(zr).mean()
                entropy_pen=(ms_entropy_penalty(hc,*clean_bound)+
                             ms_entropy_penalty(hr,*zoo_bounds[j]))
                # This is only a candidate-search surrogate. Final acceptance
                # uses all 15 reject models and the original hard conditions.
                loss=2.0*clean_preserve+reject_flip+MISENTRY_ENTROPY_PENALTY*entropy_pen
                grad=torch.autograd.grad(loss,xv,allow_unused=True)[0]
                if grad is None or not bool(torch.isfinite(grad).all()) or float(grad.norm().detach().cpu())<=1e-12:
                    break
                x=ms_project_l2(x.detach()-MISENTRY_STEP_SIZE*ms_unit_grad(grad.detach()),x0).detach()
                if step%max(1,MISENTRY_TARGETED_CHECK_EVERY)==0 or step==MISENTRY_TARGETED_STEPS:
                    # First test only the chosen pair, avoiding a full 15-model
                    # scan at every step. But never accept without the full scan.
                    if _ms_quick_promising(clean,zoo,clean_bound,zoo_bounds,x,x0,[j]):
                        candidate=ms_candidate_status(
                            clean,zoo,clean_bound,zoo_bounds,x,x0,
                            solver=f"targeted-margin[{j}]",accepted_at_step=step
                        )
                        if candidate["accepted"] and _ms_better_candidate(best,candidate):
                            best=candidate
                            return best
    return best

def _ms_mnist_entropy_repair(clean, zoo, clean_bound, zoo_bounds, x0, seed):
    """Try to repair entropy on *already disagreeing* MNIST sources.

    Never accepts a candidate unless ms_candidate_status passes unchanged
    entropy, L2, and Top-1 witness constraints on the actual final models.
    This is an optimization heuristic, not a relaxation of any threshold.
    """
    if CFG["dataset"] != "MNIST":
        return None
    x0 = x0.detach().to(MS_DEVICE).unsqueeze(0).clamp(0.0, 1.0)
    with torch.no_grad():
        zc0 = ms_logits(clean, x0)
        orig_label = int(zc0.argmax(1).item())
        witnesses = []
        for j, other in enumerate(zoo):
            zo0 = ms_logits(other, x0)
            other_label = int(zo0.argmax(1).item())
            if other_label != orig_label:
                ho = float(ms_softmax_entropy_from_logits(zo0).item())
                hgap = max(zoo_bounds[j][0] - ho, 0.0,
                           ho - zoo_bounds[j][1])
                witnesses.append((hgap, j, other_label))
    if not witnesses:
        return None
    witnesses.sort()
    for _, j, other_label in witnesses[:max(1, MISENTRY_MNIST_ENTROPY_REPAIR_MODELS)]:
        x = x0.clone()
        for step in range(1, max(1, MISENTRY_MNIST_ENTROPY_REPAIR_STEPS) + 1):
            xv = x.detach().requires_grad_(True)
            zc = ms_logits(clean, xv)
            zo = ms_logits(zoo[j], xv)
            hc = ms_softmax_entropy_from_logits(zc).mean()
            ho = ms_softmax_entropy_from_logits(zo).mean()
            # Entropy violations are normalized by each model's own calibrated
            # interval width so one loss does not swamp the other.
            pc = ms_entropy_penalty(hc, *clean_bound) / max(
                (clean_bound[1] - clean_bound[0])**2, 1e-6)
            po = ms_entropy_penalty(ho, *zoo_bounds[j]) / max(
                (zoo_bounds[j][1] - zoo_bounds[j][0])**2, 1e-6)
            maskc = torch.ones_like(zc, dtype=torch.bool)
            maskc[:, orig_label] = False
            masko = torch.ones_like(zo, dtype=torch.bool)
            masko[:, other_label] = False
            mc = zc[:, orig_label] - zc.masked_fill(~maskc, -torch.inf).max(1).values
            mo = zo[:, other_label] - zo.masked_fill(~masko, -torch.inf).max(1).values
            # Small hinge penalties maintain the already-different predictions.
            loss = pc + po + 0.2*F.relu(0.05 - mc).mean() + 0.2*F.relu(0.05 - mo).mean()
            grad = torch.autograd.grad(loss, xv, allow_unused=True)[0]
            if grad is None or not bool(torch.isfinite(grad).all()) or float(grad.norm().item()) < 1e-12:
                break
            x = ms_project_l2(x.detach() - MISENTRY_STEP_SIZE*ms_unit_grad(grad.detach()), x0).detach()
            if step % 3 == 0 or step == MISENTRY_MNIST_ENTROPY_REPAIR_STEPS:
                if _ms_quick_promising(clean, zoo, clean_bound, zoo_bounds, x, x0, [j]):
                    out = ms_candidate_status(clean, zoo, clean_bound, zoo_bounds, x, x0,
                        solver=f"mnist-entropy-repair[{j}]", accepted_at_step=step)
                    if out["accepted"]:
                        return out
    return None


def ms_optimize_fingerprint(clean,zoo,clean_bound,zoo_bounds,x0,seed):
    # A raw source already meeting all criteria is itself feasible; avoid
    # paying for 60 optimization steps before returning the same witness.
    x=x0.detach().to(MS_DEVICE).unsqueeze(0).clamp(0,1)
    initial=ms_candidate_status(clean,zoo,clean_bound,zoo_bounds,x,x,
                                solver="feasible-unmodified-source",accepted_at_step=0)
    if initial.get("accepted",False):
        return initial
    if CFG["dataset"] == "MNIST" and initial["zoo_disagreements"] > 0:
        repaired = _ms_mnist_entropy_repair(clean, zoo, clean_bound, zoo_bounds, x0, seed)
        if repaired is not None and repaired.get("accepted", False):
            return repaired
    # Prefer the original paper-equation/meta optimizer first.
    result=_ms_meta_optimize(clean,zoo,clean_bound,zoo_bounds,x0,seed)
    if result.get("accepted",False):
        return result
    # MNIST's near-identical zoo models otherwise produce very few labels
    # differing within the natural-image entropy range. Use a margin-guided
    # candidate-search fallback, not any relaxation of final acceptance.
    if CFG["dataset"]=="MNIST":
        candidate=_ms_margin_search(clean,zoo,clean_bound,zoo_bounds,x0,seed)
        if candidate is not None and candidate.get("accepted",False):
            return candidate
        if MISENTRY_MNIST_PAIRWISE_FALLBACK:
            candidate=_ms_pairwise_fallback(clean,zoo,clean_bound,zoo_bounds,x0,seed)
            if candidate is not None and candidate.get("accepted",False):
                return candidate
    return result


