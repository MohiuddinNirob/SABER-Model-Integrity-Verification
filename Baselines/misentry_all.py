        if not (clean_bound[0] <= hp <= clean_bound[1]) or l2 > MISENTRY_EPS_L2+1e-5: return False
        for j in sorted(set(int(k) for k in indices if 0<=int(k)<len(zoo))):
            zr=ms_blackbox_logits(zoo[j],x); yr=int(zr.argmax(1).item()); hr=float(ms_softmax_entropy_from_logits(zr).item())
