def _ms_validate_zoo_files(clean):
    rows=[]; bad=[]
    clean_sd={k:v.detach().cpu() for k,v in clean.state_dict().items()}
    if CFG["model"] in ("ResNet18","RNN"):
        head_prefixes=("fc.",)
    elif CFG["model"]=="MobileViT":
        head_prefixes=("classifier.",)
    else:
        head_prefixes=()
    for j,(typ,i,path) in enumerate(ms_zoo_spec_paths()):
        try:
            m=new_target_model(); raw=torch.load(path,map_location="cpu")
            sd=_normalize_state_dict(raw)
            m.load_state_dict(sd,strict=True)
            changed=[k for k,v in clean_sd.items() if not torch.equal(v,sd[k].detach().cpu())]
            scope_ok=True
            if typ=="ft_last":
                scope_ok=bool(changed) and bool(head_prefixes) and all(
                    any(k.startswith(pref) for pref in head_prefixes) for k in changed
                )
            m=m.to(MS_DEVICE).eval()
            h=_ms_health_metrics(m,clean)
            valid=(h["FiniteLogits"] and h["ClassCoverage"]>=MISENTRY_ZOO_MIN_CLASS_COVERAGE and
                   h["Accuracy"]>=MISENTRY_ZOO_MIN_ACCURACY and
                   float(h["MeanKLFromTarget"] or 0.0)>MISENTRY_ZOO_MIN_MEAN_KL and scope_ok)
            rows.append({"Type":typ,"Index":i,"Path":str(path),**h,
                         "ChangedStateTensors":len(changed),"LastLayerScopeOK":bool(scope_ok),
                         "Valid":bool(valid)})
            print(f"  [MiSentry][zoo-health] {typ}[{i}] valid={valid} acc={100*h['Accuracy']:.2f}% "
                  f"classes={h['ClassCoverage']}/10 agree={100*float(h['TargetAgreement'] or 0):.2f}% "
                  f"KL={float(h['MeanKLFromTarget'] or 0):.3e} changed={len(changed)} scope_ok={scope_ok}")
            if not valid: bad.append(j)
            del m
            if torch.cuda.is_available(): torch.cuda.empty_cache()
        except Exception as exc:
            rows.append({"Type":typ,"Index":i,"Path":str(path),"Valid":False,"Error":repr(exc)}); bad.append(j)
    save_table(pd.DataFrame(rows),"MiSentry_model_zoo_health.csv")
    return rows,bad

