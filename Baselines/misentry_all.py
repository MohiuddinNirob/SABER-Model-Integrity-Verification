def build_attack_checkpoint(mode, out):
    """Match the supplied SABER model-attack construction and RNG exactly."""
    if out.exists() and CLEAN_PATH.exists() and out.stat().st_mtime >= CLEAN_PATH.stat().st_mtime:
        return
    s = copy.deepcopy(_normalize_state_dict(torch.load(CLEAN_PATH, map_location="cpu", weights_only=False)))
    keys = float_keys(s)
    wk, bk = classifier_keys(s)
    g = None
    if CFG["model"] == "RNN":
        # Supplied RNN adapter uses the first 8 SHA256 bytes, modulo 100000.
        seed = int.from_bytes(hashlib.sha256(str(mode).encode()).digest()[:8], 'big') % 100000
        g = torch.Generator().manual_seed(SEED + seed)
    else:
        # Supplied ResNet18 and MobileViT attacks use dedicated 701/702/703 seeds.
        seeds = {"finetune": 702, "drift": 703, "corrupt10000": 15001,
                 "corrupt1000": 15002, "corrupt100": 15003}
        g = torch.Generator().manual_seed(SEED + seeds.get(mode, 701))
    with torch.no_grad():
        if mode.startswith("corrupt"):
            denom=int(mode.removeprefix("corrupt")); mag={10000:.30,1000:.25,100:.20}[denom]
            # SABER ResNet/MobileViT uses seed=SEED+denom for corruption.
            if CFG["model"] != "RNN":
                g=torch.Generator().manual_seed(SEED+denom)
            for k in keys:
                f=s[k].reshape(-1); n=max(1,f.numel()//denom)
                ix=torch.randperm(f.numel(),generator=g)[:n]
                f[ix] += mag*torch.randn(n,generator=g,dtype=f.dtype)
        elif mode == "backdoor":
            if CFG["model"] == "ResNet18":
                s["fc.bias"][0] += 3.0
                s["fc.weight"][0, ::8] += 0.25
            elif CFG["model"] == "MobileViT":
                # SABER: final floating tensor selected by _last_float_key(...,1)
                one_dim = [k for k in keys if s[k].ndim == 1]
                k = one_dim[-1] if one_dim else keys[-1]
                f = s[k].reshape(-1)
                f[0] += 3.0
                if f.numel() > 8: f[::8] += 0.25
            else:
                k=keys[-1]; s[k].reshape(-1)[:min(32,s[k].numel())] += 0.25
        elif mode == "finetune":
            if CFG["model"] == "ResNet18":
                tail = [k for k in keys if k.startswith("layer4") or k.startswith("fc")]
            elif CFG["model"] == "MobileViT":
                tail = keys[max(0,len(keys)-max(2,len(keys)//4)):]
            else:
                tail = keys[-max(1,len(keys)//4):]
            for k in tail:
                s[k] += 0.002*torch.randn(s[k].shape,generator=g,dtype=s[k].dtype)
        elif mode == "early":
            k = "conv1.weight" if CFG["model"] == "ResNet18" else keys[0]
            f=s[k].reshape(-1)
            if CFG["model"] == "ResNet18": step=97
            elif CFG["model"] == "MobileViT": step=max(1,f.numel()//128)
            else: step=max(1,f.numel()//100)
            f[::step] += 0.15
        elif mode == "drift":
            if CFG["model"] == "ResNet18":
                k="fc.weight"; s[k] += 0.03*torch.randn(s[k].shape,generator=g,dtype=s[k].dtype)
            elif CFG["model"] == "RNN":
                for k in ("fc.weight","fc.bias"):
                    s[k] += 0.03*torch.randn(s[k].shape,generator=g,dtype=s[k].dtype)
            else:
                k=keys[-1]; s[k] += 0.03*torch.randn(s[k].shape,generator=g,dtype=s[k].dtype)
        elif mode == "bias":
            if CFG["model"] == "MobileViT":
                one_dim=[k for k in keys if s[k].ndim==1]
                k=one_dim[-1] if one_dim else keys[-1]
            else:
                k=bk if bk is not None else keys[-1]
            s[k].reshape(-1)[::2] += .08
        elif mode == "scale":
            if wk is None or bk is None:
                raise RuntimeError("SABER requires both classifier weight and bias for positive-logit scaling")
            s[wk] *= SCALE_FACTOR; s[bk] *= SCALE_FACTOR
        elif mode == "compression":
            eligible=[(k,t) for k,t in s.items()
                      if torch.is_tensor(t) and torch.is_floating_point(t) and t.ndim>=2 and t.numel()]
            if CFG["model"] == "MobileViT":
                if not eligible: raise RuntimeError("No eligible MobileViT pruning tensors")
                values=torch.cat([t.detach().abs().reshape(-1).float() for _,t in eligible])
                rank=max(1,min(values.numel(),int(round(.30*values.numel()))))
                threshold=float(torch.kthvalue(values,rank).values)
                for k,t in eligible: t[t.abs() <= threshold]=0
            else:
                for k,w in eligible:
                    maxabs=float(w.abs().max())
                    if maxabs>0:
                        step=maxabs/127.0
                        s[k]=(torch.clamp(torch.round(w/step),-127,127)*step).to(w.dtype)
        else:
            raise ValueError(f"Unknown SABER attack: {mode}")
    tmp=Path(str(out)+".tmp")
    torch.save(s,tmp); tmp.replace(out)


