def wilson(k, n, z=1.959963984540054):
    if n <= 0: return float('nan'), float('nan')
    p = k/n; den=1+z*z/n; c=(p+z*z/(2*n))/den
    h=z*math.sqrt((p*(1-p)/n)+z*z/(4*n*n))/den
    return max(0,c-h), min(1,c+h)

