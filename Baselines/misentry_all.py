def _all8_completed(root, cfg):
    rdir = root / cfg / "results"
    marker = rdir / "_MISENTRY_COMPLETE"
    manifest = rdir / "MiSentry_manifest.json"
    if not (marker.exists() and manifest.exists()):
        return False
    try:
        m = json.loads(marker.read_text())
        d = json.loads(manifest.read_text())
    except Exception:
        return False
    version = str(d.get("version", m.get("version", "")))
    # v13 modifies MNIST fingerprint-search ordering/repair and the
    # MobileViT differentiable forward. Previously validated v12 completed
    # configurations have identical evaluation and acceptance logic and
    # remain valid and should not be needlessly retrained.
    allowed = {ALL8_EXPECTED_VERSION}
