def _ms_rank_source_ids(clean, zoo, clean_bound, zoo_bounds, ids):
    """Full-zoo source feasibility ranking, *without* changing hard checks.

    v10 consulted only zoo indices [0, 5, 10] even when asked to scout
    all 15. In MNIST these three often agree with the clean model despite
    other zoo members disagreeing. Rank actually feasible sources first,
    followed by valid-entropy candidates with high model disagreement/KL.
    Keep every source in the permutation and round-robin within each bucket
    to avoid concentrating all fingerprints in one class.
    """
    if not MISENTRY_SOURCE_RANKING or len(ids) <= 1 or not zoo:
        return ids
    pool_n=min(len(ids), max(0,int(MISENTRY_SOURCE_RANK_POOL)))
    if pool_n<=1:
        return ids
    pool,rest=ids[:pool_n],ids[pool_n:]
    m=max(1,min(int(MISENTRY_SOURCE_RANK_MODELS),len(zoo)))
    per=max(1,int(MISENTRY_ZOO_MODELS_PER_TYPE))
    # Interleave all three zoo families. In particular, m=15 means ALL 15.
    zidx=[]
    for i in range(per):
        for typ in range(3):
            j=typ*per+i
            if j<len(zoo): zidx.append(j)
    zidx=(zidx+[j for j in range(len(zoo)) if j not in zidx])[:m]
    buckets={i:{} for i in range(5)}
    stats={"Pool":pool_n,"ScoutedZoo":len(zidx),"RawFeasible":0,
           "CleanEntropyOK":0,"AnyTop1Disagreement":0,"AnyWitness":0,
           "DisagreementAndCleanEntropyOK":0}
    t0=time.perf_counter(); bs=max(1,int(MISENTRY_SOURCE_RANK_BATCH))
    with torch.no_grad():
        for st in range(0,len(pool),bs):
            chunk=pool[st:st+bs]
            xb=torch.stack([RAW_TEST[j][0] for j in chunk])
            zc=ms_blackbox_logits(clean,xb)
            hp=ms_softmax_entropy_from_logits(zc); yl=zc.argmax(1)
            cp=torch.softmax(zc,dim=-1).clamp_min(1e-12)
            clean_ok=(hp>=clean_bound[0])&(hp<=clean_bound[1])
            any_diff=torch.zeros(len(chunk),device=zc.device,dtype=torch.bool)
            any_witness=torch.zeros_like(any_diff)
            kl_max=torch.zeros(len(chunk),device=zc.device)
            for j in zidx:
                zr=ms_blackbox_logits(zoo[j],xb)
                hr=ms_softmax_entropy_from_logits(zr)
                disagree=zr.argmax(1)!=yl
                any_diff|=disagree
                any_witness|=(disagree & (hr>=zoo_bounds[j][0]) & (hr<=zoo_bounds[j][1]))
                pr=torch.softmax(zr,dim=-1).clamp_min(1e-12)
                kl=((cp*(cp.log()-pr.log())).sum(dim=1)).clamp_min(0)
                kl_max=torch.maximum(kl_max,kl)
            good=clean_ok&any_witness
            stats["RawFeasible"]+=int(good.sum().item())
            stats["CleanEntropyOK"]+=int(clean_ok.sum().item())
            stats["AnyTop1Disagreement"]+=int(any_diff.sum().item())
            stats["AnyWitness"]+=int(any_witness.sum().item())
            stats["DisagreementAndCleanEntropyOK"]+=int((any_diff&clean_ok).sum().item())
            co=clean_ok.detach().cpu().tolist()
            go=good.detach().cpu().tolist()
            wo=any_witness.detach().cpu().tolist()
            di=any_diff.detach().cpu().tolist()
            hs=hp.detach().cpu().tolist()
            ks=kl_max.detach().cpu().tolist()
            for idx,ok,g,w,d,h,kl in zip(chunk,co,go,wo,di,hs,ks):
                # v12 accidentally buried actual disagreement images behind
                # thousands of clean-entropy-valid but label-identical images.
                # Attempt genuinely disagreeing sources first, especially ones
                # whose clean entropy needs only a small correction.
                bucket=(0 if g else 1 if w else 2 if d and ok else
                        3 if d else 4)
                hgap=max(clean_bound[0]-h,0.0,h-clean_bound[1])
                hwidth=max(float(clean_bound[1]-clean_bound[0]),1e-5)
                score=(5.0 if ok else 0.0) + 0.1*float(kl) - hgap/hwidth
                buckets[bucket].setdefault(int(RAW_TEST[idx][1]),[]).append((idx,score))
    ranked=[]
    for bucket in range(5):
        by_class=buckets[bucket]
        for v in by_class.values(): v.sort(key=lambda z:z[1],reverse=True)
        classes=sorted(by_class)
        while any(by_class[c] for c in classes):
            for c in classes:
                if by_class[c]: ranked.append(by_class[c].pop(0)[0])
    rank_summary={**stats,"RankingSeconds":round(time.perf_counter()-t0,3),
                  "CriteriaUnchanged":True,"AllSourcesRetained":True}
    try:
        (RESULT_DIR/"MiSentry_source_ranking_diagnostic.json").write_text(json.dumps(rank_summary,indent=2))
    except Exception as exc:
        print("  [MiSentry][diagnostic] Could not save source ranking:",exc)
    print(f"  [MiSentry] source ranking: {pool_n} sources, ALL {len(zidx)} chosen zoo models, "
          f"raw-feasible={stats['RawFeasible']}, clean-entropy-ok={stats['CleanEntropyOK']}, "
          f"zoo-disagreement={stats['AnyTop1Disagreement']}, "
          f"disagree+clean-entropy={stats['DisagreementAndCleanEntropyOK']}, "
          f"feasible-zoo-witness={stats['AnyWitness']}; "
          f"{rank_summary['RankingSeconds']:.2f}s; zero sources discarded")
    return ranked+rest


def ms_generate_bank(clean, zoo, zoo_meta, clean_bound, zoo_bounds):
    ms_refresh_paths()
    images, labels, records = [], [], []
    if FP_BANK_PATH.exists():
        try:
            d = torch.load(FP_BANK_PATH, map_location="cpu")
            if (d.get("configuration") == MS_CONFIG and d.get("version") == MISENTRY_VERSION
                    and d.get("cache_tag") == MISENTRY_CACHE_TAG
                    and d.get("cache_settings") == ms_cache_payload()):
                images = [t.clone() for t in d["images"]]
                labels = [int(v) for v in d["labels"].tolist()]
                records = list(d.get("records", []))
                print(f"  [MiSentry] Resuming bank {len(images)}/{MISENTRY_FINGERPRINTS}: {FP_BANK_PATH}")
        except Exception as exc:
            print("  [MiSentry] Existing bank ignored:", exc)
            images, labels, records = [], [], []

    if len(images) >= MISENTRY_FINGERPRINTS:
        return {"images":torch.stack(images[:MISENTRY_FINGERPRINTS]),
                "labels":torch.tensor(labels[:MISENTRY_FINGERPRINTS]),"records":records}, 0.0

    init_raw_data()
    rng = random.Random(SEED + 70071)
    ids = list(range(len(RAW_TEST)))
    rng.shuffle(ids)
    ids = _ms_rank_source_ids(clean, zoo, clean_bound, zoo_bounds, ids)
    # Cycle deterministically if more attempts than test samples.
    attempts = 0
    reject_counts = {}
    used_source_ids={int(r.get("SourceIndex",-1)) for r in records}
    t0 = time.perf_counter()
    while len(images) < MISENTRY_FINGERPRINTS and attempts < MISENTRY_MAX_SOURCE_ATTEMPTS:
        idx = ids[attempts % len(ids)]
        if idx in used_source_ids:
            # Resumed/revalidated banks must not contain duplicate source images.
            attempts += 1
            continue
        x0, y0 = RAW_TEST[idx]
        out = ms_optimize_fingerprint(
            clean, zoo, clean_bound, zoo_bounds, x0,
            seed=SEED * 1000003 + attempts * 97 + idx
        )
        attempts += 1
        if not out["accepted"]:
            rr=str(out.get("reject_reason","rejected")); reject_counts[rr]=reject_counts.get(rr,0)+1
            if attempts % 25 == 0:
                print(f"    bank={len(images):3d}/{MISENTRY_FINGERPRINTS} attempts={attempts} rejects={reject_counts}")
            if attempts == MISENTRY_ZERO_BANK_DIAGNOSTIC_AFTER and len(images) == 0:
                diagnostic={"Status":"ZERO_ACCEPTED_FINGERPRINTS","Configuration":MS_CONFIG,
                            "SourceAttempts":attempts,"AcceptedFingerprints":0,
                            "RejectCounts":reject_counts,"EpsilonL2":MISENTRY_EPS_L2,
                            "PGDSteps":MISENTRY_PGD_STEPS,"TargetedFallback":MISENTRY_TARGETED_FALLBACK,
                            "TargetedModels":MISENTRY_TARGETED_MODELS,
                            "FinalConstraintsRelaxed":False}
                (RESULT_DIR/"MiSentry_zero_bank_diagnostic.json").write_text(
                    json.dumps(diagnostic,indent=2),encoding="utf-8")
                print("  [MiSentry][diagnostic] No valid fingerprints yet. Top-1 disagreement is a required hard condition; no fallback will bypass it.")
                print("  [MiSentry][diagnostic] Compare source-feasibility, per-zoo target agreement, and MNIST epsilon before committing to a longer run.")
                if MISENTRY_STOP_IF_ZERO_BANK:
                    raise RuntimeError(
                        f"Zero feasible fingerprints after {attempts} attempts; rejects={reject_counts}. "
                        "This is an optimization/feasibility failure, not a measured ADR. "
                        "The original model zoo remains cached. Set MISENTRY_STOP_IF_ZERO_BANK=0 to continue searching. "
                        "Do not relax the required Top-1 or entropy constraints to force a result."
                    )
            continue
        images.append(out.pop("image"))
        labels.append(int(out.pop("label")))
        used_source_ids.add(int(idx))
        rec = {"BankIndex":len(images)-1,"SourceIndex":idx,"SourceClass":int(y0),**out}
        wi = rec.get("witness_index")
        if wi is not None and 0 <= int(wi) < len(zoo_meta):
            rec["WitnessType"] = zoo_meta[int(wi)]["Type"]
            rec["WitnessModelIndex"] = zoo_meta[int(wi)]["Index"]
        records.append(rec)
        print(
            f"    accepted bank={len(images):3d}/{MISENTRY_FINGERPRINTS} "
            f"source={idx} L2={rec['l2']:.4f} zoo_disagree={rec['zoo_disagreements']}"
        )
        if len(images) % MISENTRY_SAVE_EVERY == 0:
            ms_save_bank(images, labels, records, FP_BANK_PATH)

    elapsed = time.perf_counter() - t0
    if len(images) < MISENTRY_FINGERPRINTS:
        ms_save_bank(images, labels, records, FP_BANK_PATH)
        raise RuntimeError(
            f"MiSentry generated only {len(images)}/{MISENTRY_FINGERPRINTS} accepted fingerprints "
            f"after {attempts} source attempts. Rejection counts={reject_counts}. Inspect the "
            "explicit PGD/epsilon settings and MobileViT preflight diagnostics before changing them."
        )
    ms_save_bank(images, labels, records, FP_BANK_PATH)
    save_table(pd.DataFrame(records), "MiSentry_fingerprint_generation.csv")
    return {"images":torch.stack(images),"labels":torch.tensor(labels),"records":records}, elapsed

