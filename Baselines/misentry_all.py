def ms_entropy_penalty(h, lo, hi):
    return F.relu(torch.as_tensor(lo, device=h.device, dtype=h.dtype) - h).pow(2) + \
           F.relu(h - torch.as_tensor(hi, device=h.device, dtype=h.dtype)).pow(2)

def ms_pair_loss(clean, reject, x, clean_bound, reject_bound):
    zp = ms_logits(clean, x)
    zr = ms_logits(reject, x)
    kl = ms_kl_p_r(zp, zr).mean()
    hp = ms_softmax_entropy_from_logits(zp).mean()
    hr = ms_softmax_entropy_from_logits(zr).mean()
    cp = ms_entropy_penalty(hp, clean_bound[0], clean_bound[1])
    cr = ms_entropy_penalty(hr, reject_bound[0], reject_bound[1])
    loss = (
        -kl
        + MISENTRY_LAMBDA_P * hp
        + MISENTRY_LAMBDA_R * hr
        + MISENTRY_ENTROPY_PENALTY * globals().get("MISENTRY_CONSTRAINT_MULTIPLIER",1.0) * (cp + cr)
    )
    return loss, {
        "KL": float(kl.detach().cpu()),
        "Hp": float(hp.detach().cpu()),
        "Hr": float(hr.detach().cpu()),
    }

def ms_unit_grad(g):
    flat = g.reshape(g.shape[0], -1)
    n = flat.norm(dim=1, keepdim=True).clamp_min(1e-12)
    return (flat / n).reshape_as(g)

def ms_project_l2(x, x0):
    d = x - x0
    flat = d.reshape(d.shape[0], -1)
    n = flat.norm(dim=1, keepdim=True).clamp_min(1e-12)
    scale = torch.clamp(MISENTRY_EPS_L2 / n, max=1.0)
    d = (flat * scale).reshape_as(d)
    return (x0 + d).clamp(0.0, 1.0)


def ms_candidate_status(clean, zoo, clean_bound, zoo_bounds, x, x0, solver="meta", accepted_at_step=None):
    """Evaluate MiSentry's hard Eq. (3) constraints plus the Top-1 witness."""
    with torch.no_grad():
        zp = ms_blackbox_logits(clean, x)
        target_label = int(zp.argmax(1).item())
        hp = float(ms_softmax_entropy_from_logits(zp).item())
        clean_ok = bool(clean_bound[0] <= hp <= clean_bound[1])
        top1_dis = 0
        feasible = []
        kl_vals = []
        for j, r in enumerate(zoo):
            zr = ms_blackbox_logits(r, x)
            lbl = int(zr.argmax(1).item())
            hr = float(ms_softmax_entropy_from_logits(zr).item())
            kl_vals.append(float(ms_kl_p_r(zp, zr).item()))
            if lbl != target_label:
                top1_dis += 1
                if zoo_bounds[j][0] <= hr <= zoo_bounds[j][1]:
                    feasible.append((j, lbl, hr))
        l2 = float((x-x0).reshape(-1).norm().item())
    witness = feasible[0] if feasible else None
    accepted = bool(clean_ok and witness is not None and l2 <= MISENTRY_EPS_L2 + 1e-5)
    if hp < clean_bound[0]:
        reason = "clean_entropy_low"
    elif hp > clean_bound[1]:
        reason = "clean_entropy_high"
    elif top1_dis == 0:
        reason = "no_top1_zoo_disagreement"
    elif witness is None:
        reason = "reject_entropy_outside"
    elif l2 > MISENTRY_EPS_L2 + 1e-5:
        reason = "l2"
    else:
        reason = "accepted"
    return {
        "image":x.squeeze(0).detach().cpu(),
        "label":target_label,
        "accepted":accepted,
        "clean_entropy":hp,
        "l2":l2,
        "witness_index":None if witness is None else int(witness[0]),
        "witness_label":None if witness is None else int(witness[1]),
        "witness_entropy":None if witness is None else float(witness[2]),
        "zoo_disagreements":int(top1_dis),
        "feasible_witnesses":int(len(feasible)),
        "mean_kl_to_zoo":float(np.mean(kl_vals)) if kl_vals else 0.0,
        "reject_reason":reason,
        "solver":solver,
        "accepted_at_step":accepted_at_step,
    }

def _ms_better_candidate(a, b):
    if a is None:
        return True
    sb=(int(b.get("feasible_witnesses",0)),float(b.get("mean_kl_to_zoo",0.0)),-float(b.get("l2",1e9)))
    sa=(int(a.get("feasible_witnesses",0)),float(a.get("mean_kl_to_zoo",0.0)),-float(a.get("l2",1e9)))
    return sb > sa

def _ms_meta_optimize(clean, zoo, clean_bound, zoo_bounds, x0, seed):
    rng = random.Random(int(seed))
    x0 = x0.detach().to(MS_DEVICE).unsqueeze(0).clamp(0,1)
    x = x0.clone()
    n_zoo = len(zoo)
    if n_zoo < 2:
        raise RuntimeError("MiSentry model zoo must contain at least two rejected models")
    best = None
    last = {}
    c0 = ms_candidate_status(clean,zoo,clean_bound,zoo_bounds,x,x0,solver="meta",accepted_at_step=0)
    if c0["accepted"]:
        best = c0
    for step in range(MISENTRY_PGD_STEPS):
        order = list(range(n_zoo)); rng.shuffle(order)
        s_n = min(max(1, MISENTRY_META_TRAIN_MODELS), max(1, n_zoo-1))
        q_n = min(max(1, MISENTRY_META_TEST_MODELS), n_zoo-s_n)
        support = order[:s_n]
        query = order[s_n:s_n+q_n] or [order[-1]]

        xv = x.detach().requires_grad_(True)
        losses = [ms_pair_loss(clean, zoo[j], xv, clean_bound, zoo_bounds[j])[0] for j in support]
        loss_s = torch.stack(losses).mean()
        gs = torch.autograd.grad(loss_s, xv, retain_graph=False, create_graph=False, allow_unused=True)[0]
        if gs is None or (not torch.isfinite(gs).all()) or float(gs.norm().detach().cpu()) <= 1e-12:
            out = ms_candidate_status(clean,zoo,clean_bound,zoo_bounds,x,x0,solver="meta",accepted_at_step=step)
            out["reject_reason"] = "invalid_support_gradient"
            return best if best is not None else out

        x_inner = ms_project_l2(
            xv.detach() - MISENTRY_META_INNER_STEP * ms_unit_grad(gs.detach()), x0
        ).detach().requires_grad_(True)

        q_losses = []
        for j in query:
            lq, info = ms_pair_loss(clean, zoo[j], x_inner, clean_bound, zoo_bounds[j])
            q_losses.append(lq); last = info
        loss_q = torch.stack(q_losses).mean()
        gq = torch.autograd.grad(loss_q, x_inner, retain_graph=False, create_graph=False, allow_unused=True)[0]
        if gq is None or (not torch.isfinite(gq).all()) or float(gq.norm().detach().cpu()) <= 1e-12:
            out = ms_candidate_status(clean,zoo,clean_bound,zoo_bounds,x,x0,solver="meta",accepted_at_step=step)
            out["reject_reason"] = "invalid_query_gradient"
            return best if best is not None else out

        direction = ms_unit_grad(gs.detach()) + MISENTRY_META_WEIGHT * ms_unit_grad(gq.detach())
        direction = ms_unit_grad(direction)
        x = ms_project_l2(x.detach() - MISENTRY_STEP_SIZE * direction, x0).detach()

        if ((step+1) % max(1, MISENTRY_FEASIBILITY_EVERY) == 0) or step+1 == MISENTRY_PGD_STEPS:
            c = ms_candidate_status(clean,zoo,clean_bound,zoo_bounds,x,x0,solver="meta",accepted_at_step=step+1)
            if c["accepted"] and _ms_better_candidate(best,c):
                best = c
    if best is not None:
        best.update(last)
        return best
    out = ms_candidate_status(clean,zoo,clean_bound,zoo_bounds,x,x0,solver="meta",accepted_at_step=MISENTRY_PGD_STEPS)
    out.update(last)
    return out

def _ms_pairwise_fallback(clean, zoo, clean_bound, zoo_bounds, x0, seed):
    """Direct Eq. (3)-(5) pairwise fallback for difficult image classifiers.

    The main paper defines the optimization for one protected/rejected model pair
    before introducing meta-learning. This fallback uses that exact pairwise form,
    while still selecting only candidates satisfying the hard entropy and L2
    constraints against the full model zoo.
    """
    x0 = x0.detach().to(MS_DEVICE).unsqueeze(0).clamp(0,1)
    nper=max(1,int(MISENTRY_ZOO_MODELS_PER_TYPE))
    order=[]
    for i in range(nper):
        for base in (0,nper,2*nper):
            j=base+i
            if j < len(zoo): order.append(j)
    order=order[:min(len(order),int(MISENTRY_MNIST_PAIRWISE_MODELS))]
    best=None
    for oi,j in enumerate(order):
        for restart in range(max(1,int(MISENTRY_MNIST_PAIRWISE_RESTARTS))):
            x=x0.clone()
            if restart>0:
                tg=torch.Generator().manual_seed(int(seed)+1009*oi+7919*restart)
                noise=torch.randn(x.shape,generator=tg).to(MS_DEVICE)
                noise=ms_unit_grad(noise)*min(0.10*MISENTRY_EPS_L2,0.10)
                x=ms_project_l2(x0+noise,x0).detach()
            c0=ms_candidate_status(clean,zoo,clean_bound,zoo_bounds,x,x0,solver=f"pairwise[{j}]",accepted_at_step=0)
            if c0["accepted"] and _ms_better_candidate(best,c0): best=c0
            for step in range(int(MISENTRY_MNIST_PAIRWISE_STEPS)):
                xv=x.detach().requires_grad_(True)
                loss,_=ms_pair_loss(clean,zoo[j],xv,clean_bound,zoo_bounds[j])
                g=torch.autograd.grad(loss,xv,allow_unused=True)[0]
                if g is None or (not torch.isfinite(g).all()) or float(g.norm().detach().cpu())<=1e-12:
                    break
                x=ms_project_l2(x.detach()-MISENTRY_STEP_SIZE*ms_unit_grad(g.detach()),x0).detach()
                if ((step+1)%max(1,MISENTRY_FEASIBILITY_EVERY)==0) or step+1==MISENTRY_MNIST_PAIRWISE_STEPS:
                    c=ms_candidate_status(clean,zoo,clean_bound,zoo_bounds,x,x0,
                                          solver=f"pairwise[{j}]",accepted_at_step=step+1)
                    if c["accepted"] and _ms_better_candidate(best,c):
                        best=c
                        if int(c.get("feasible_witnesses",0))>=2:
                            return best
            if best is not None:
                return best
    return best

def ms_optimize_fingerprint(clean, zoo, clean_bound, zoo_bounds, x0, seed):
    out=_ms_meta_optimize(clean,zoo,clean_bound,zoo_bounds,x0,seed)
    if out.get("accepted",False):
        return out
    if CFG["dataset"]=="MNIST" and MISENTRY_MNIST_PAIRWISE_FALLBACK:
        alt=_ms_pairwise_fallback(clean,zoo,clean_bound,zoo_bounds,x0,seed)
        if alt is not None and alt.get("accepted",False):
            return alt
    return out

