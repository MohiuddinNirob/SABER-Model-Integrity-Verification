def _ms_meta_optimize(clean,zoo,clean_bound,zoo_bounds,x0,seed):
    rng=random.Random(int(seed)); x0=x0.detach().to(MS_DEVICE).unsqueeze(0).clamp(0,1); x=x0.clone(); n_zoo=len(zoo)
    if n_zoo<2: raise RuntimeError("MiSentry model zoo must contain at least two rejected models")
    best=None; last={}; c0=ms_candidate_status(clean,zoo,clean_bound,zoo_bounds,x,x0,solver="meta",accepted_at_step=0)
    if c0["accepted"]: best=c0
    for step in range(MISENTRY_PGD_STEPS):
        order=list(range(n_zoo)); rng.shuffle(order); s_n=min(max(1,MISENTRY_META_TRAIN_MODELS),max(1,n_zoo-1)); q_n=min(max(1,MISENTRY_META_TEST_MODELS),n_zoo-s_n); support=order[:s_n]; query=order[s_n:s_n+q_n] or [order[-1]]
        xv=x.detach().requires_grad_(True); losses=[ms_pair_loss(clean,zoo[j],xv,clean_bound,zoo_bounds[j])[0] for j in support]; loss_s=torch.stack(losses).mean(); gs=torch.autograd.grad(loss_s,xv,allow_unused=True)[0]
        if gs is None or (not torch.isfinite(gs).all()) or float(gs.norm().detach().cpu())<=1e-12:
            out=ms_candidate_status(clean,zoo,clean_bound,zoo_bounds,x,x0,solver="meta",accepted_at_step=step); out["reject_reason"]="invalid_support_gradient"; return best if best is not None else out
        x_inner=ms_project_l2(xv.detach()-MISENTRY_META_INNER_STEP*ms_unit_grad(gs.detach()),x0).detach().requires_grad_(True); q_losses=[]
        for j in query: lq,last=ms_pair_loss(clean,zoo[j],x_inner,clean_bound,zoo_bounds[j]); q_losses.append(lq)
        loss_q=torch.stack(q_losses).mean(); gq=torch.autograd.grad(loss_q,x_inner,allow_unused=True)[0]
        if gq is None or (not torch.isfinite(gq).all()) or float(gq.norm().detach().cpu())<=1e-12:
            out=ms_candidate_status(clean,zoo,clean_bound,zoo_bounds,x,x0,solver="meta",accepted_at_step=step); out["reject_reason"]="invalid_query_gradient"; return best if best is not None else out
        direction=ms_unit_grad(ms_unit_grad(gs.detach())+MISENTRY_META_WEIGHT*ms_unit_grad(gq.detach())); x=ms_project_l2(x.detach()-MISENTRY_STEP_SIZE*direction,x0).detach()
        check=((step+1)%max(1,MISENTRY_FEASIBILITY_EVERY)==0) or step+1==MISENTRY_PGD_STEPS
        if check and (step+1==MISENTRY_PGD_STEPS or _ms_quick_promising(clean,zoo,clean_bound,zoo_bounds,x,x0,support+query)):
            c=ms_candidate_status(clean,zoo,clean_bound,zoo_bounds,x,x0,solver="meta",accepted_at_step=step+1)
            if c["accepted"] and _ms_better_candidate(best,c): best=c
    if best is not None: best.update(last); return best
    out=ms_candidate_status(clean,zoo,clean_bound,zoo_bounds,x,x0,solver="meta",accepted_at_step=MISENTRY_PGD_STEPS); out.update(last); return out

