def _ms_health_metrics(model, clean=None, n=None):
    ids=_ms_health_ids(n or MISENTRY_HEALTH_SAMPLES)
    preds=[]; ys=[]; finite=True; agrees=0; total=0; kl_sum=0.0
    with torch.no_grad():
        for st in range(0,len(ids),32):
            jj=ids[st:st+32]
            x=torch.stack([RAW_TEST[k][0] for k in jj])
            y=torch.tensor([int(RAW_TEST[k][1]) for k in jj])
            z=ms_blackbox_logits(model,x)
            if not torch.isfinite(z).all(): finite=False
            p=z.argmax(1).detach().cpu(); preds.extend(p.tolist()); ys.extend(y.tolist())
            if clean is not None:
                zc=ms_blackbox_logits(clean,x); pc=zc.argmax(1).detach().cpu()
                agrees += int((p==pc).sum()); total += len(jj)
                kl_sum += float(ms_kl_p_r(zc,z).sum().detach().cpu())
    acc=float(np.mean(np.asarray(preds)==np.asarray(ys))) if preds else 0.0
    classes=len(set(int(v) for v in preds))
    hist={int(k):int(v) for k,v in zip(*np.unique(np.asarray(preds,dtype=int),return_counts=True))} if preds else {}
    return {"FiniteLogits":bool(finite),"Accuracy":acc,"ClassCoverage":classes,"PredHistogram":hist,
            "TargetAgreement":None if clean is None else agrees/max(1,total),
            "MeanKLFromTarget":None if clean is None else kl_sum/max(1,total),"Samples":len(preds)}

