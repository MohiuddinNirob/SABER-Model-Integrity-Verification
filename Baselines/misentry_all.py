class ImageRNN(nn.Module):
    def __init__(self, dataset):
        super().__init__(); self.dataset=dataset; hidden=128
        inp=96 if dataset=='CIFAR10' else 28
        self.rnn=nn.RNN(inp,hidden,num_layers=2,batch_first=True,nonlinearity='tanh')
        self.norm=nn.LayerNorm(hidden); self.fc=nn.Linear(hidden,10)
    def sequence(self,x):
        if self.dataset=='CIFAR10':
            x=x.permute(0,2,1,3).contiguous(); return x.reshape(x.shape[0],32,96)
        return x[:,0,:,:]
    def forward(self,x):
        y,_=self.rnn(self.sequence(x)); return self.fc(self.norm(y[:,-1,:]))


