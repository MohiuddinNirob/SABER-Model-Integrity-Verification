def architecture_substitution():
    """Primary AS transformations as written in the supplied SABER sources."""
    m=load_target(CLEAN_PATH).to(MS_DEVICE).eval()
    if CFG["model"] == "ResNet18":
        # SABER: layer2.0.conv1, 3x3 -> 5x5, old kernel in center.
        conv=m.layer2[0].conv1
        if not isinstance(conv,nn.Conv2d) or conv.kernel_size!=(3,3):
            raise RuntimeError("Unexpected ResNet18 SABER architecture-substitution target")
        repl=nn.Conv2d(conv.in_channels,conv.out_channels,5,stride=conv.stride,
                       padding=2,dilation=conv.dilation,groups=conv.groups,
                       bias=conv.bias is not None,padding_mode=conv.padding_mode).to(conv.weight.device,conv.weight.dtype)
        with torch.no_grad():
            repl.weight.zero_(); repl.weight[:,:,1:4,1:4]=conv.weight
            if conv.bias is not None: repl.bias.copy_(conv.bias)
        m.layer2[0].conv1=repl
    else:
        # SABER RNN and MobileViT: original linear followed by an executed
        # equal-width Linear initialized as exact identity (bias=False).
        if CFG["model"] == "RNN":
            parent=m; name="fc"
        elif CFG["model"] == "MobileViT":
            parent=m; name="classifier"
        else: raise RuntimeError("AS only for original image classification families")
        original=getattr(parent,name)
        if not isinstance(original,nn.Linear):
            raise RuntimeError(f"SABER AS expected nn.Linear at {name}")
        identity=nn.Linear(original.out_features,original.out_features,bias=False).to(original.weight.device,original.weight.dtype)
        with torch.no_grad():
            identity.weight.copy_(torch.eye(original.out_features,device=original.weight.device,dtype=original.weight.dtype))
        setattr(parent,name,nn.Sequential(original,identity))
    return m.eval()


def ms_candidate_status(clean,zoo,clean_bound,zoo_bounds,x,x0,solver="meta-pgd",
                        accepted_at_step=None, candidate_pair=None):
    """Enforce MiSentry Eq.(3), NOT an extra Top-1-disagreement constraint.

    Feasible if L2 bound, target entropy bound, and rejected-model entropy
    bound for at least one member of the representative model zoo hold.
    KL is the optimization/selection score, not an imposed published cutoff.
    """
    with torch.no_grad():
        zp=ms_blackbox_logits(clean,x)
        hp=float(ms_softmax_entropy_from_logits(zp).item())
        pred=int(zp.argmax(1).item())
        l2=float((x-x0).reshape(-1).norm().item())
        e_ok=bool(clean_bound[0]<=hp<=clean_bound[1])
        p=torch.softmax(zp,dim=-1).clamp_min(1e-12)
        feasible=[]; all_kl=[]; all_dis=0
        for j,z in enumerate(zoo):
            zr=ms_blackbox_logits(z,x)
            q=torch.softmax(zr,dim=-1).clamp_min(1e-12)
            kl=float((p*(p.log()-q.log())).sum(dim=1).item())
            hr=float(ms_softmax_entropy_from_logits(zr).item())
            all_kl.append(kl)
            if int(zr.argmax(1).item())!=pred: all_dis+=1
            if zoo_bounds[j][0]<=hr<=zoo_bounds[j][1]:
                feasible.append((j,kl,hr))
    eligible=feasible if candidate_pair is None else [v for v in feasible if v[0]==candidate_pair]
    ok=bool(e_ok and bool(eligible) and l2<=MISENTRY_EPS_L2+1e-5)
    preferred=max(eligible,key=lambda it:it[1]) if eligible else None
    return {
        "image":x.squeeze(0).detach().cpu(),"label":pred,"accepted":ok,
        "clean_entropy":hp,"l2":l2,
        "witness_index":preferred[0] if preferred else None,
        "witness_label":None,"witness_entropy":preferred[2] if preferred else None,
        "zoo_disagreements":all_dis,
        "feasible_witnesses":len(feasible),
        "mean_kl_to_zoo":float(np.mean(all_kl)) if all_kl else 0.,
        "feasible_mean_kl":float(np.mean([v[1] for v in eligible])) if eligible else 0.,
        "feasible_max_kl":max((v[1] for v in eligible),default=0.),
        "reject_reason":("accepted" if ok else "l2" if l2>MISENTRY_EPS_L2+1e-5 else
                         "target_entropy" if not e_ok else "no_rejected_model_entropy_in_range"),
        "solver":solver,"accepted_at_step":accepted_at_step,
        "Top1ZooDisagreementRequired":False,
    }


def _ms_better_candidate(a,b):
    if b is None or not b.get("accepted",False): return False
    if a is None or not a.get("accepted",False): return True
    sb=(b.get("feasible_mean_kl",0.),b.get("feasible_max_kl",0.),-b.get("l2",0.))
    sa=(a.get("feasible_mean_kl",0.),a.get("feasible_max_kl",0.),-a.get("l2",0.))
    return sb>sa


def _ms_rank_source_ids(clean,zoo,clean_bound,zoo_bounds,ids):
    """Prioritize entropy-feasible sources with larger KL, not Top-1 flips.

    This is an efficiency/source-diversity heuristic; ALL sources are retained.
    """
    if not MISENTRY_SOURCE_RANKING or len(ids)<2: return ids
    pool_n=min(len(ids),max(0,int(MISENTRY_SOURCE_RANK_POOL)))
    if pool_n<=1: return ids
    pool,remaining=ids[:pool_n],ids[pool_n:]
    scout=list(range(min(len(zoo),max(1,int(MISENTRY_SOURCE_RANK_MODELS)))))
    ranked=[]; bs=max(1,int(MISENTRY_SOURCE_RANK_BATCH))
    with torch.no_grad():
        for start in range(0,len(pool),bs):
            chunk=pool[start:start+bs]
            xb=torch.stack([RAW_TEST[i][0] for i in chunk])
            zp=ms_blackbox_logits(clean,xb)
            hp=ms_softmax_entropy_from_logits(zp)
            prob=torch.softmax(zp,dim=1).clamp_min(1e-12)
            valid_p=(hp>=clean_bound[0]) & (hp<=clean_bound[1])
            vals=torch.zeros(len(chunk),device=zp.device)
            hits=torch.zeros(len(chunk),device=zp.device,dtype=torch.long)
            for j in scout:
                zr=ms_blackbox_logits(zoo[j],xb)
                hr=ms_softmax_entropy_from_logits(zr)
                ok=(hr>=zoo_bounds[j][0])&(hr<=zoo_bounds[j][1])
                pr=torch.softmax(zr,dim=1).clamp_min(1e-12)
                div=(prob*(prob.log()-pr.log())).sum(1).clamp_min(0)
                vals+=torch.where(ok,div,0.)
                hits+=ok.long()
            for k,idx in enumerate(chunk):
                score=float(vals[k]/max(1,int(hits[k])))
                # Prefer feasibility across many zoo models but maintain
                # KL-driven quality; no preference for Top1 flips.
                category=0 if bool(valid_p[k]) and int(hits[k]) else 1
                ranked.append((category,-score,int(RAW_TEST[idx][1]),idx))
    # distribute selected inputs across source classes, then quality
    ranked.sort(key=lambda t:(t[0],t[1]))
    buckets={c:[] for c in range(10)}
    for cat,neg,c,idx in ranked: buckets[c].append((cat,neg,idx))
    output=[]
    while any(buckets.values()):
        for c in sorted(buckets):
            if buckets[c]: output.append(buckets[c].pop(0)[2])
    print(f"  [MiSentry] Eq.(3) source screening: {pool_n} candidates, "
          f"{len(scout)} zoo models, KL priority; no Top-1 gate")
    return output+remaining


def ms_optimize_fingerprint(clean,zoo,clean_bound,zoo_bounds,x0,seed):
    """First-order meta-learning-inspired PGD for Eqs.(1)-(5).

    This is a transparent *reimplementation* of the published loss.
    The full original MiSentry meta-learning update code is not public.
    No targeted-margin/entropy-repair fallback is used.
    """
    rng=random.Random(int(seed))
    x0=x0.detach().to(MS_DEVICE).unsqueeze(0).clamp(0.,1.)
    x=x0.detach().clone(); best=None
    for step in range(1,max(1,MISENTRY_PGD_STEPS)+1):
        order=list(range(len(zoo))); rng.shuffle(order)
        ns=min(max(1,MISENTRY_META_TRAIN_MODELS),len(zoo)-1)
        nq=min(max(1,MISENTRY_META_TEST_MODELS),len(zoo)-ns)
        support=order[:ns]; query=order[ns:ns+nq]
        xv=x.detach().requires_grad_(True)
        ls=torch.stack([ms_pair_loss(clean,zoo[j],xv,clean_bound,zoo_bounds[j])[0]
                        for j in support]).mean()
        gs=torch.autograd.grad(ls,xv,allow_unused=True)[0]
        if gs is None or not bool(torch.isfinite(gs).all()) or float(gs.norm())<=1e-12: break
        inner=ms_project_l2(x.detach()-MISENTRY_META_INNER_STEP*ms_unit_grad(gs.detach()),x0)
        qi=inner.detach().requires_grad_(True)
        lq=torch.stack([ms_pair_loss(clean,zoo[j],qi,clean_bound,zoo_bounds[j])[0]
                        for j in query]).mean()
        gq=torch.autograd.grad(lq,qi,allow_unused=True)[0]
        if gq is None or not bool(torch.isfinite(gq).all()) or float(gq.norm())<=1e-12: break
        d=ms_unit_grad(ms_unit_grad(gs.detach())+MISENTRY_META_WEIGHT*ms_unit_grad(gq.detach()))
        x=ms_project_l2(x.detach()-MISENTRY_STEP_SIZE*d,x0).detach()
        if step%max(1,MISENTRY_FEASIBILITY_EVERY)==0 or step==MISENTRY_PGD_STEPS:
            candidate=ms_candidate_status(clean,zoo,clean_bound,zoo_bounds,x,x0,
                                           solver="meta-PGD-Eq3",accepted_at_step=step)
            if _ms_better_candidate(best,candidate): best=candidate
    # Prefer the strongest feasible optimization iterate, not the first
    # unmodified source simply satisfying entropy bounds.
    if best is not None: return best
    return ms_candidate_status(clean,zoo,clean_bound,zoo_bounds,x,x0,
                               solver="meta-PGD-Eq3",accepted_at_step=MISENTRY_PGD_STEPS)


def _ms_bank_health(clean,zoo,bank):
    imgs=bank["images"]; labels=bank["labels"]
    n=min(int(MISENTRY_BANK_VALIDATE_SAMPLES),len(imgs))
    if n<=0: return {"Valid":False,"Reason":"empty_bank"}
    x=imgs[:n]
    finite=bool(torch.isfinite(x).all()); inrange=bool((x>=-1e-6).all() and (x<=1+1e-6).all())
    got=ms_top1(clean,x); correct=float((got==labels[:n].cpu()).float().mean())
    # The original paper does not require a zoo Top-1 mismatch. Report as
    # diagnostic only; never include in the bank validity decision.
    mask=torch.zeros(n,dtype=torch.bool)
    for z in zoo: mask |= ms_top1(z,x)!=labels[:n].cpu()
    disagreement=float(mask.float().mean())
    valid=finite and inrange and correct==1.0
    row={"Valid":bool(valid),"SamplesChecked":n,"Finite":finite,
         "InRange01":inrange,"EnrollmentLabelAgreement":correct,
         "CurrentZooDisagreementRateDiagnosticOnly":disagreement,
         "Top1ZooDisagreementRequired":False}
    save_table(pd.DataFrame([row]),"MiSentry_fingerprint_bank_health.csv")
    print(f"  [MiSentry] bank health: valid={valid}, clean-label-match={100*correct:.1f}%, "
          f"zoo-Top1-disagreement(diagnostic)={100*disagreement:.1f}%")
    return row


def ms_generate_bank(clean,zoo,zoo_meta,clean_bound,zoo_bounds):
    """New fingerprint cache/validation, without importing v10-v13 banks."""
    ms_refresh_paths(); images=[]; labels=[]; records=[]
    if FP_BANK_PATH.exists():
        try:
            raw=torch.load(FP_BANK_PATH,map_location="cpu",weights_only=False)
            if (raw.get("version")==MISENTRY_VERSION and
                raw.get("configuration")==MS_CONFIG and
                raw.get("cache_tag")==MISENTRY_CACHE_TAG and
                raw.get("cache_settings")==ms_cache_payload()):
                images=[v.clone() for v in raw["images"]]
                labels=list(map(int,raw["labels"]))
                records=list(raw.get("records",[]))
                print(f"  [MiSentry] Resuming v14 Eq.(3) bank {len(images)}/{MISENTRY_FINGERPRINTS}")
        except Exception as exc:
            print(f"  [MiSentry] Old fingerprint bank rejected: {exc}")
    if len(images)>=MISENTRY_FINGERPRINTS:
        bank={"images":torch.stack(images[:MISENTRY_FINGERPRINTS]),
              "labels":torch.tensor(labels[:MISENTRY_FINGERPRINTS]),"records":records}
        if not _ms_bank_health(clean,zoo,bank)["Valid"]: raise RuntimeError("Cached v14 bank failed health")
        return bank,0.0
    init_raw_data(); rng=random.Random(SEED+70071)
    ids=list(range(len(RAW_TEST))); rng.shuffle(ids)
    ids=_ms_rank_source_ids(clean,zoo,clean_bound,zoo_bounds,ids)
    used={int(r.get("SourceIndex",-1)) for r in records}
    attempted=0; rejected={}; t0=time.perf_counter()
    for idx in ids:
        if len(images)>=MISENTRY_FINGERPRINTS or attempted>=MISENTRY_MAX_SOURCE_ATTEMPTS: break
        if idx in used: continue
        x0,y0=RAW_TEST[idx]; attempted+=1
        cand=ms_optimize_fingerprint(clean,zoo,clean_bound,zoo_bounds,x0,
                                     seed=SEED*1000003+attempted*97+idx)
        if not cand["accepted"]:
            reason=cand.get("reject_reason","unknown")
            rejected[reason]=rejected.get(reason,0)+1
            if attempted%25==0: print(f"    bank={len(images)}/{MISENTRY_FINGERPRINTS}, attempts={attempted}, rejects={rejected}")
            continue
        images.append(cand.pop("image")); labels.append(int(cand.pop("label"))); used.add(idx)
        rec={"BankIndex":len(images)-1,"SourceIndex":idx,"SourceClass":int(y0),**cand}
        wi=rec.get("witness_index")
        if wi is not None and 0<=wi<len(zoo_meta):
            rec["RepresentativeType"]=zoo_meta[wi]["Type"]
            rec["RepresentativeIndex"]=zoo_meta[wi]["Index"]
        records.append(rec)
        print(f"    accepted bank={len(images):3d}/{MISENTRY_FINGERPRINTS} source={idx} "
              f"L2={rec['l2']:.4f} KL={rec['feasible_mean_kl']:.6f} "
              f"zoo_top1_diff={rec['zoo_disagreements']} (not required)")
        if len(images)%MISENTRY_SAVE_EVERY==0:
            ms_save_bank(images,labels,records,FP_BANK_PATH)
    elapsed=time.perf_counter()-t0
    ms_save_bank(images,labels,records,FP_BANK_PATH)
    if len(images)<MISENTRY_FINGERPRINTS:
        raise RuntimeError(f"Only {len(images)}/{MISENTRY_FINGERPRINTS} Eq.(3)-feasible fingerprints "
                           f"after {attempted} sources; rejections={rejected}. No results fabricated.")
    bank={"images":torch.stack(images),"labels":torch.tensor(labels),"records":records}
    if not _ms_bank_health(clean,zoo,bank)["Valid"]:
        raise RuntimeError("New Eq.(3) bank health check failed")
    save_table(pd.DataFrame(records),"MiSentry_fingerprint_generation.csv")
    return bank,elapsed

