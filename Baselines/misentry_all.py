def build_attack_checkpoint(mode, out):
    if out.exists() and CLEAN_PATH.exists() and out.stat().st_mtime>=CLEAN_PATH.stat().st_mtime: return
    s=copy.deepcopy(torch.load(CLEAN_PATH,map_location='cpu')); keys=float_keys(s); g=torch.Generator().manual_seed(SEED+int.from_bytes(hashlib.sha256(mode.encode()).digest()[:4],'big')%100000)
    wk,bk=classifier_keys(s)
    if mode.startswith('corrupt'):
        denom=int(mode.replace('corrupt','')); mag={10000:.30,1000:.25,100:.20}[denom]
        for k in keys:
            f=s[k].reshape(-1); n=max(1,f.numel()//denom); ix=torch.randperm(f.numel(),generator=g)[:n]; f[ix]+=mag*torch.randn(n,generator=g,dtype=f.dtype)
    elif mode=='backdoor':
        if CFG['model']=='ResNet18' and wk and bk:
            s[bk][0]+=3.0; s[wk][0,::8]+=0.25
        elif CFG['model']=='MobileViT':
            k=keys[-1]; f=s[k].reshape(-1); f[0]+=3.0; f[::8]+=0.25
        else:
            k=keys[-1]; s[k].reshape(-1)[:min(32,s[k].numel())]+=0.25
    elif mode=='finetune':
        tail = [k for k in keys if k.startswith('layer4') or k.startswith('fc')] if CFG['model']=='ResNet18' else keys[-max(1,len(keys)//4):]
        for k in tail: s[k]+=0.002*torch.randn(s[k].shape,generator=g,dtype=s[k].dtype)
    elif mode=='early':
        k='conv1.weight' if CFG['model']=='ResNet18' else keys[0]; f=s[k].reshape(-1); step=97 if CFG['model']=='ResNet18' else max(1,f.numel()//128); f[::step]+=0.15
    elif mode=='drift':
        if CFG['model'] in ('ResNet18','RNN') and wk:
            s[wk]+=0.03*torch.randn(s[wk].shape,generator=g,dtype=s[wk].dtype)
            if CFG['model']=='RNN' and bk: s[bk]+=0.03*torch.randn(s[bk].shape,generator=g,dtype=s[bk].dtype)
        else:
            k=keys[-1]; s[k]+=0.03*torch.randn(s[k].shape,generator=g,dtype=s[k].dtype)
    elif mode=='bias':
        k=bk or keys[-1]; s[k].reshape(-1)[::2]+=0.08
    elif mode=='scale':
        if wk: s[wk]*=SCALE_FACTOR
        if bk: s[bk]*=SCALE_FACTOR
    elif mode=='compression':
        if CFG['model']=='MobileViT':
            elig=[(k,t) for k,t in s.items() if torch.is_tensor(t) and torch.is_floating_point(t) and t.ndim>=2 and t.numel()>0]
            mags=torch.cat([t.abs().reshape(-1).float() for _,t in elig]); kk=max(1,int(round(.30*mags.numel()))); th=float(torch.kthvalue(mags,kk).values)
            for k,t in elig: t[t.abs()<=th]=0
        else:
            for k in keys:
                w=s[k]
                if w.ndim<2: continue
                ma=float(w.abs().max());
                if ma<=0: continue
                sc=ma/127.; q=torch.clamp(torch.round(w/sc),-127,127); s[k]=(q*sc).to(w.dtype)
    else: raise ValueError(mode)
    torch.save(s,out)


