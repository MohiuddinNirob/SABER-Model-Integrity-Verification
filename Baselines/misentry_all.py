def network_transfer(payload_bytes, profile, rng):
    delivered = rng.random() >= profile.packet_loss
    rtt = rng.uniform(*profile.rtt_ms) + rng.gauss(0.0, profile.jitter_ms)
    tx = (8.0*payload_bytes)/(profile.bandwidth_mbps*1e6)*1000.0
    return delivered, max(0.0,rtt)+tx

