def ms_softmax_entropy_from_logits(logits):
    p = torch.softmax(logits, dim=-1).clamp_min(1e-12)
    return -(p * p.log()).sum(dim=-1)

def ms_kl_p_r(logits_p, logits_r):
    p = torch.softmax(logits_p, dim=-1).clamp_min(1e-12)
    r = torch.softmax(logits_r, dim=-1).clamp_min(1e-12)
    return (p * (p.log() - r.log())).sum(dim=-1)

def _ms_processor_size_dict(value):
    """Convert int, Mapping, or HF SizeDict to an ordinary size mapping.

    Recent Transformers exposes image processor sizes as SizeDict objects with
    height/width/shortest_edge attributes, not necessarily a subclass of dict.
    """
    from collections.abc import Mapping
    if value is None:
        return {}
    if isinstance(value, (int, float)):
        return {"height": int(value), "width": int(value)}
    if isinstance(value, Mapping):
        return {str(k): v for k, v in value.items() if v is not None}
    for method in ("to_dict", "model_dump"):
        fn = getattr(value, method, None)
        if callable(fn):
            converted = fn()
            if isinstance(converted, Mapping):
                return {str(k): v for k, v in converted.items() if v is not None}
    result = {k: getattr(value, k) for k in
              ("height", "width", "shortest_edge", "longest_edge")
              if getattr(value, k, None) is not None}
    if not result:
        raise TypeError(f"Unsupported MobileViT processor size: {type(value).__name__}: {value!r}")
    return result


def _ms_resize_shape(size, old_height, old_width):
    """Resolve Hugging Face resize sizes, keeping aspect ratio if specified."""
    if "height" in size and "width" in size:
        return int(size["height"]), int(size["width"])
    if "shortest_edge" in size:
        edge = int(size["shortest_edge"])
        if old_height <= old_width:
            h, w = edge, max(1, int(round(old_width * edge / old_height)))
        else:
            h, w = max(1, int(round(old_height * edge / old_width))), edge
        limit = size.get("longest_edge")
        if limit is not None and max(h, w) > int(limit):
            factor = int(limit) / max(h, w)
            h, w = max(1, int(round(h * factor))), max(1, int(round(w * factor)))
        return h, w
    raise ValueError(f"Unsupported MobileViT resize size fields: {size}")


def ms_mobilevit_preprocess(raw_batch):
    """Differentiable approximation of the actual MobileViT image processor.

    Inputs here are ToTensor RGB data in [0,1]. This already incorporates the
    processor's usual PIL uint8 -> float32 / 255 rescaling. Do not rescale
    them a second time. The separate service/black-box path continues to use
    AutoImageProcessor itself, and preflight checks Top-1 consistency.
    """
    if PROCESSOR is None:
        init_raw_data()
    x = raw_batch.to(MS_DEVICE)
    if getattr(PROCESSOR, "do_resize", True):
        size = _ms_processor_size_dict(getattr(PROCESSOR, "size", None))
        if size:
            h, w = _ms_resize_shape(size, int(x.shape[-2]), int(x.shape[-1]))
            if (h, w) != tuple(x.shape[-2:]):
                x = F.interpolate(x, size=(h, w), mode="bicubic",
                                  align_corners=False, antialias=True)
    if getattr(PROCESSOR, "do_center_crop", False):
        crop = _ms_processor_size_dict(getattr(PROCESSOR, "crop_size", None))
        if crop:
            h = int(crop.get("height", crop.get("shortest_edge", x.shape[-2])))
            w = int(crop.get("width", crop.get("shortest_edge", x.shape[-1])))
            if h <= 0 or w <= 0:
                raise ValueError("MobileViT crop dimensions must be positive")
            # HF pads symmetrically when the requested center crop is larger.
            dh, dw = max(0, h - int(x.shape[-2])), max(0, w - int(x.shape[-1]))
            if dh or dw:
                x = F.pad(x, (dw//2, (dw+1)//2, dh//2, (dh+1)//2))
            top = max(0, (int(x.shape[-2]) - h) // 2)
            left = max(0, (int(x.shape[-1]) - w) // 2)
            x = x[..., top:top+h, left:left+w]
    # MobileViTImageProcessor defaults to RGB-to-BGR conversion. In the
    # previous code, omitting this could make white-box gradients disagree
    # with the enrolled AutoImageProcessor's service-path predictions.
    if bool(getattr(PROCESSOR, "do_flip_channel_order", False)):
        if x.shape[1] < 3:
            raise ValueError("MobileViT channel flipping requires >=3 channels")
        x = torch.cat((x[:, 2:3], x[:, 1:2], x[:, 0:1], x[:, 3:]), dim=1)
    if bool(getattr(PROCESSOR, "do_normalize", False)):
        mean = torch.as_tensor(getattr(PROCESSOR, "image_mean", [0.5,0.5,0.5]),
                               device=x.device, dtype=x.dtype).view(1,-1,1,1)
        std = torch.as_tensor(getattr(PROCESSOR, "image_std", [0.5,0.5,0.5]),
                              device=x.device, dtype=x.dtype).view(1,-1,1,1)
        x = (x - mean) / std
    return x

def ms_logits(model, raw_batch):
    """Differentiable white-box logits used only for fingerprint optimization."""
    raw_batch = raw_batch.to(MS_DEVICE)
    if CFG["model"] == "MobileViT":
        # Forward uses the SAME AutoImageProcessor as the black-box service.
        # Its PIL/uint8 conversion is not differentiable. During PGD, use a
        # straight-through / BPDA gradient through the approximate tensor
        # processor, but take exact service-path pixels for the forward pass.
        # Thus validation and the optimized forward evaluate identical inputs;
        # gradients remain an explicitly documented approximation.
        if torch.is_grad_enabled() and raw_batch.requires_grad:
            surrogate = ms_mobilevit_preprocess(raw_batch)
            with torch.no_grad():
                exact = _ms_mobilevit_exact_pixels(raw_batch)
            if surrogate.shape != exact.shape:
                raise RuntimeError(
                    f"MobileViT BPDA dimensions disagree: surrogate={tuple(surrogate.shape)}, "
                    f"AutoImageProcessor={tuple(exact.shape)}."
                )
            pixels = surrogate + (exact - surrogate).detach()
        else:
            pixels = _ms_mobilevit_exact_pixels(raw_batch)
        return model(pixel_values=pixels).logits
    # cuDNN's fused RNN backward is unsupported if forward ran in eval mode.
    # Fingerprint PGD requires input gradients but must keep the enrolled model
    # in eval mode. Use the native autograd RNN kernel for *gradient* forwards;
    # ordinary inference and black-box Top-1 checks remain unchanged.
    if CFG["model"] == "RNN" and torch.is_grad_enabled() and raw_batch.requires_grad:
        with torch.backends.cudnn.flags(enabled=False):
            return model(normalize_for_target(raw_batch))
    return model(normalize_for_target(raw_batch))

def _ms_mobilevit_exact_pixels(raw_batch):
    """Unmodified service preprocessing; PIL forward is deliberately non-diff."""
    if PROCESSOR is None:
        init_raw_data()
    imgs = [TF.to_pil_image(x.detach().cpu().clamp(0, 1)) for x in raw_batch]
    return PROCESSOR(images=imgs, return_tensors="pt")["pixel_values"].to(MS_DEVICE)


def ms_blackbox_logits(model, raw_batch):
    """Actual service-path logits used for enrollment, calibration and verification."""
    if CFG["model"] == "MobileViT":
        return target_logits(model, raw_batch)
    return ms_logits(model, raw_batch)

def ms_top1(model, raw_batch):
    with torch.no_grad():
        return ms_blackbox_logits(model, raw_batch).argmax(dim=1).detach().cpu()

def ms_mobilevit_preflight(clean):
    if CFG["model"] != "MobileViT":
        return
    init_raw_data()
    n = min(20, len(RAW_TEST_POOL))
    batch = torch.stack(RAW_TEST_POOL[:n]).to(MS_DEVICE)
    standard = target_top1(clean, batch)
    with torch.no_grad():
        approximate = clean(pixel_values=ms_mobilevit_preprocess(batch)).logits.argmax(1).cpu()
        exact_forward = ms_logits(clean, batch).argmax(1).cpu()
    approx_agreement = float((standard == approximate).float().mean().item())
    agree = float((standard == exact_forward).float().mean().item())
    print(f"  [MiSentry] MobileViT differentiable surrogate Top-1 agreement="
          f"{100*approx_agreement:.1f}% ({n} samples); approximate gradients only")
    print(f"  [MiSentry] MobileViT exact-forward Top-1 agreement="
          f"{100*agree:.1f}% ({n} samples); AutoImageProcessor used for forward")
    if agree < 1.0:
        raise RuntimeError("MobileViT forward preprocessing must exactly match the service path.")
    probe=torch.stack(RAW_TEST_POOL[:1]).to(MS_DEVICE).detach().requires_grad_(True)
    val=ms_softmax_entropy_from_logits(ms_logits(clean,probe)).sum()
    grad=torch.autograd.grad(val,probe,allow_unused=True)[0]
    if grad is None or (not torch.isfinite(grad).all()) or float(grad.norm().detach().cpu()) <= 1e-12:
        raise RuntimeError("MobileViT differentiable preprocessing produced no usable input gradient.")
    print(f"  [MiSentry] MobileViT input-gradient preflight: PASS (L2={float(grad.norm().detach().cpu()):.6g})")

def ms_last_layer(model):
    if CFG["model"] in ("ResNet18", "RNN"):
        return model.fc
    if CFG["model"] == "MobileViT":
        return model.classifier
    raise RuntimeError("No classification head for this configuration")

def ms_reset_all_trainable(model):
    # Random-start retraining: reset modules that expose reset_parameters().
    for module in model.modules():
        fn = getattr(module, "reset_parameters", None)
        if callable(fn):
            try:
                fn()
            except Exception:
                pass
    return model

def ms_train_batches(model, train_last_only, lr, epochs, seed):
    init_raw_data()
    model = model.to(MS_DEVICE)
    if train_last_only:
        for p in model.parameters():
            p.requires_grad_(False)
        for p in ms_last_layer(model).parameters():
            p.requires_grad_(True)
    else:
        for p in model.parameters():
            p.requires_grad_(True)

    params = [p for p in model.parameters() if p.requires_grad]
    opt = torch.optim.Adam(params, lr=float(lr))
    dl = DataLoader(
        RAW_TRAIN, batch_size=MISENTRY_ZOO_BATCH, shuffle=True,
        num_workers=2, pin_memory=torch.cuda.is_available(),
        generator=torch.Generator().manual_seed(int(seed))
    )
    for ep in range(int(epochs)):
        if train_last_only:
            # Keep the frozen backbone in eval mode so BatchNorm/dropout state
            # cannot silently turn "last-layer fine-tuning" into a backbone change.
            model.eval()
            ms_last_layer(model).train()
        else:
            model.train()
        seen = good = 0
        loss_sum = 0.0
        for bi, (xb, yb) in enumerate(dl):
            if MISENTRY_ZOO_MAX_BATCHES > 0 and bi >= MISENTRY_ZOO_MAX_BATCHES:
                break
            xb = xb.to(MS_DEVICE, non_blocking=True)
            yb = yb.to(MS_DEVICE, non_blocking=True)
            opt.zero_grad(set_to_none=True)
            logits = target_logits(model, xb)
            loss = F.cross_entropy(logits, yb)
            loss.backward()
            if CFG["model"] == "RNN":
                torch.nn.utils.clip_grad_norm_(params, 5.0)
            opt.step()
            seen += int(yb.numel())
            good += int((logits.argmax(1) == yb).sum().item())
            loss_sum += float(loss.detach().cpu()) * int(yb.numel())
        print(
            f"      epoch {ep+1}/{epochs}: loss={loss_sum/max(1,seen):.6f}, "
            f"train_acc={100.0*good/max(1,seen):.2f}%"
        )
    model.eval()
    return model

